CREATE TABLE departamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    orcamento_total NUMERIC(14,2) NOT NULL,
    valor_comprometido NUMERIC(14,2) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_departamento_nome_nao_vazio CHECK (LENGTH(TRIM(nome)) > 0),
    CONSTRAINT ck_departamento_orcamento_positivo CHECK (orcamento_total > 0),
    CONSTRAINT ck_departamento_comprometido_ok CHECK (valor_comprometido >= 0 AND valor_comprometido <= orcamento_total)
);

CREATE TABLE solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departamento_id BIGINT NOT NULL REFERENCES departamento (id),
    descricao VARCHAR(500) NOT NULL,
    valor NUMERIC(14,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_solicitacao_descricao_nao_vazia CHECK (LENGTH(TRIM(descricao)) > 0),
    CONSTRAINT ck_solicitacao_valor_positivo CHECK (valor > 0),
    CONSTRAINT ck_solicitacao_status_valido CHECK (status IN ('PENDENTE','APROVADA','REJEITADA'))
);

CREATE TABLE historico_solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL REFERENCES solicitacao (id),
    status_anterior VARCHAR(20) NOT NULL,
    status_novo VARCHAR(20) NOT NULL,
    responsavel VARCHAR(120) NOT NULL,
    justificativa VARCHAR(500),
    criado_em TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_historico_status_anterior_valido CHECK (status_anterior IN ('PENDENTE','APROVADA','REJEITADA')),
    CONSTRAINT ck_historico_responsavel_nao_vazio CHECK (LENGTH(TRIM(responsavel)) > 0),
    CONSTRAINT ck_historico_status_novo_valido CHECK (status_novo IN ('PENDENTE','APROVADA','REJEITADA')),
    CONSTRAINT ck_historico_transicao_valida CHECK (
        (status_anterior = 'PENDENTE' AND status_novo IN ('APROVADA','REJEITADA'))
    ),
    CONSTRAINT ck_historico_rejeicao_justificativa CHECK (status_novo <> 'REJEITADA' OR (justificativa IS NOT NULL AND LENGTH(TRIM(justificativa)) > 0)),
    CONSTRAINT uq_historico_solicitacao_decisao UNIQUE (solicitacao_id)
);
